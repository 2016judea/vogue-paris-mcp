// Copies the live site's issue list into lib/snapshot.js. The server reads the live list first
// and falls back to this copy, so a slow or broken site never empties the connector.
import { writeFileSync } from "node:fs";
const r = await fetch("https://vogue-paris.vercel.app/data/issues.json");
const issues = await r.json();
writeFileSync(new URL("../lib/snapshot.js", import.meta.url),
  `// Generated by scripts/snapshot.mjs from vogue-paris.vercel.app/data/issues.json. Do not edit.\nexport default ${JSON.stringify(issues)};\n`);
console.log(`snapshot: ${issues.length} issues`);
